import { describe, expect, test } from "bun:test";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { Command } from "commander";
import { register } from "../../src/commands/init.ts";
import { ghopHome, initFile, toShellPath } from "../../src/core/paths.ts";
import { INIT_VERSION, renderInit, writeInitFile } from "../../src/shell/init.ts";
import { withTempHome } from "../helpers/env.ts";

describe("shell init rendering", () => {
  for (const shell of ["bash", "zsh"] as const) {
    test(`${shell} renders quoted roots and a current LF-only header`, () => {
      const root = "/tmp/young grasshopper's/$HOME/`echo nope`/__ROOT__";
      const content = renderInit(shell, root);
      expect(content.startsWith(`# ghop-init v${INIT_VERSION} (generated by \`ghop init ${shell}\`;`)).toBe(true);
      expect(content).toContain(`__ghop_home='/tmp/young grasshopper'\\''s/$HOME/\`echo nope\`/__ROOT__'`);
      expect(content).not.toContain("\r");
      expect(content.endsWith("\n")).toBe(true);
    });

    test(`${shell} writes the rendered default root`, () => withTempHome(() => {
      process.env.GRASSHOPPER_HOME = join(ghopHome(), "root's space");
      writeInitFile(shell);
      expect(readFileSync(initFile(shell), "utf8")).toBe(renderInit(shell, toShellPath(ghopHome(), shell)));
    }));

    test(`${shell} command prints the exact template with a verbatim root`, async () => withTempHome(async () => {
      const program = new Command();
      register(program);
      const original = process.stdout.write;
      let printed = "";
      process.stdout.write = ((chunk: string | Uint8Array) => {
        printed += typeof chunk === "string" ? chunk : new TextDecoder().decode(chunk);
        return true;
      }) as typeof process.stdout.write;
      try {
        await program.parseAsync(["init", shell, "--root", "C:/verbatim root's/$HOME"], { from: "user" });
      } finally {
        process.stdout.write = original;
      }
      expect(printed).toBe(renderInit(shell, "C:/verbatim root's/$HOME"));
    }));
  }
});
