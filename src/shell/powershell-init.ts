export const POWERSHELL_INIT = `# ghop-init v3 (generated by \`ghop init powershell\`; ghop rewrites this file when its version changes)
$__ghop_cli = [Environment]::GetCommandLineArgs()
$__ghop_batch = @($__ghop_cli | Where-Object { $_ -match '^-(NonI|Command|c$|EncodedCommand|e$|ec$|File|f$)' }).Count -gt 0
$__ghop_noexit = @($__ghop_cli | Where-Object { $_ -match '^-NoExit$' }).Count -gt 0
$__ghop_noninteractive = @($__ghop_cli | Where-Object { $_ -match '^-NonI' }).Count -gt 0
if (-not $env:GHOP_DISABLE -and -not $env:CI -and $env:TERM -ne 'dumb' -and -not $__ghop_noninteractive -and (-not $__ghop_batch -or $__ghop_noexit) -and -not (Get-Variable __ghop_home -Scope Global -ErrorAction SilentlyContinue)) {
  $global:__ghop_home = '__ROOT__'
  $global:__ghop_started = $false
  $global:__ghop_command = Get-Command ghop -CommandType Application,ExternalScript -ErrorAction SilentlyContinue | Select-Object -First 1
  $global:__ghop_session = [Guid]::NewGuid().ToString('N')
  $global:__ghop_pending = $null
  $global:__ghop_recorded_id = 0
  $global:__ghop_capture_installed = $false
  $global:__ghop_nudges = @()

  function global:__ghop_nudge {
    param([string]$Text)
    $best = ''; $chosen = ''; $seen = ' '
    for ($i = $global:__ghop_nudges.Count - 2; $i -ge 0; $i -= 2) {
      $command = $global:__ghop_nudges[$i]; $name = $global:__ghop_nudges[$i + 1]
      if ($seen.IndexOf(" $name ", [StringComparison]::OrdinalIgnoreCase) -ge 0) { continue }
      $seen += "$name "
      if ($Text -ceq $command -or ($Text.StartsWith($command, [StringComparison]::Ordinal) -and $Text.Length -gt $command.Length -and [char]::IsWhiteSpace($Text[$command.Length]))) {
        if ($command.Length -gt $best.Length) { $best = $command; $chosen = $name }
      }
    }
    if ($chosen) { Write-Host "ghop: use $chosen instead of $best" }
  }

  function global:__ghop_install_capture {
    if ($global:__ghop_capture_installed -or -not (Get-Command Get-PSReadLineOption -ErrorAction SilentlyContinue)) { return }
    $__ghop_options = Get-PSReadLineOption
    if (-not ($__ghop_options.PSObject.Properties.Name -contains 'AddToHistoryHandler')) { return }
    $global:__ghop_original_history_handler = $__ghop_options.AddToHistoryHandler
    Set-PSReadLineOption -AddToHistoryHandler {
      param([string]$line)
      $decision = $true
      if ($global:__ghop_original_history_handler) { $decision = $global:__ghop_original_history_handler.Invoke($line) }
      $global:__ghop_pending = $null
      try {
        $options = Get-PSReadLineOption
        $allowed = (($decision -is [bool] -and $decision) -or ($null -ne $decision -and $decision.ToString() -eq 'MemoryAndFile'))
        if ($allowed -and $options.HistorySaveStyle.ToString() -ne 'SaveNothing' -and -not [string]::IsNullOrWhiteSpace($line) -and $line -notmatch '(?i)(^|[;&|\\s])(?:ghop|__ghop_\\w+)(?:\\s|$)') {
          $native = $false
          $tokens = $null; $errors = $null
          $ast = [Management.Automation.Language.Parser]::ParseInput($line, [ref]$tokens, [ref]$errors)
          $statement = $ast.EndBlock.Statements | Select-Object -Last 1
          if ($statement -is [Management.Automation.Language.PipelineAst]) {
            $last = $statement.PipelineElements | Select-Object -Last 1
            if ($last -is [Management.Automation.Language.CommandAst]) {
              $name = $last.GetCommandName()
              if ($name) {
                $resolved = Get-Command -Name $name -ErrorAction SilentlyContinue | Select-Object -First 1
                $native = $resolved -and $resolved.CommandType.ToString() -in @('Application', 'ExternalScript')
              }
            }
          }
          $global:__ghop_pending = @{
            text = $line; cwd = (Get-Location).ProviderPath; file = $options.HistorySavePath
            acceptedTs = [DateTimeOffset]::UtcNow.ToUnixTimeMilliseconds() / 1000.0
            acceptedTick = [Diagnostics.Stopwatch]::GetTimestamp()
            native = $native; previousExit = $global:LASTEXITCODE; previousError = $global:Error[0]
          }
        }
      } catch { $global:__ghop_pending = $null }
      return $decision
    }
    $global:__ghop_capture_installed = $true
  }

  function global:__ghop_record {
    param([bool]$Succeeded, $NativeCode, $CommandError = $global:Error[0], $CompletedTick = [Diagnostics.Stopwatch]::GetTimestamp())
    $pending = $global:__ghop_pending
    $global:__ghop_pending = $null
    if (-not $pending) { return }
    $elapsed = ($CompletedTick - $pending.acceptedTick) / [double][Diagnostics.Stopwatch]::Frequency
    $item = Get-History -Count 1
    if (-not $item -or $item.Id -le $global:__ghop_recorded_id -or $item.CommandLine -ne $pending.text) { return }
    $global:__ghop_recorded_id = $item.Id
    __ghop_nudge $pending.text
    if (-not $global:__ghop_command) { return }
    $code = 0
    if (-not $Succeeded -or $item.ExecutionStatus.ToString() -ne 'Completed' -or ($pending.native -and $NativeCode)) {
      $code = 1
      if ($NativeCode -and ($pending.native -or $NativeCode -ne $pending.previousExit)) { $code = [int]$NativeCode }
      if ($CommandError -and -not [object]::ReferenceEquals($CommandError, $pending.previousError)) {
        $exception = $CommandError.Exception
        while ($exception) {
          if ($exception -is [Management.Automation.CommandNotFoundException]) { $code = 127; break }
          $exception = $exception.InnerException
        }
      }
    }
    $duration = ($item.EndExecutionTime - $item.StartExecutionTime).TotalSeconds
    $started = ([DateTimeOffset]$item.StartExecutionTime).ToUnixTimeMilliseconds() / 1000.0
    # Nested engine invocations can omit history timing. Measure acceptance to
    # prompt in that case, never time spent waiting at the preceding prompt.
    if ($duration -le 0) { $duration = [Math]::Max(0, $elapsed); $started = $pending.acceptedTs }
    $capture = @{
      version = 1; text = $pending.text
      acceptedTs = $pending.acceptedTs
      ts = $started; durationSec = $duration
      exitCode = $code; cwd = $pending.cwd; sessionId = $global:__ghop_session; file = $pending.file
    }
    $OutputEncoding = [Text.UTF8Encoding]::new($false)
    ConvertTo-Json -InputObject $capture -Compress | & $global:__ghop_command record powershell *> $null
  }
  $env:GHOP_SHELL = 'powershell'
  $env:GHOP_POWERSHELL = (Get-Process -Id $PID).Path
  $env:GHOP_POWERSHELL_PROFILE = $PROFILE.CurrentUserAllHosts
  $__ghop_managed = Join-Path $global:__ghop_home 'managed/powershell.ps1'
  if (Test-Path -LiteralPath $__ghop_managed) { . $__ghop_managed }

  function global:ghop {
    if (-not $global:__ghop_command) { throw 'ghop executable was not found on PATH.' }
    & $global:__ghop_command @args
    $__ghop_code = Get-Variable LASTEXITCODE -ValueOnly -ErrorAction SilentlyContinue
    $__ghop_reload = Join-Path $global:__ghop_home 'reload.powershell.ps1'
    try {
      if (Test-Path -LiteralPath $__ghop_reload) {
        . $__ghop_reload
        Remove-Item -LiteralPath $__ghop_reload -Force
      }
    } finally { $global:LASTEXITCODE = $__ghop_code }
  }

  function global:__ghop_daily {
    param($HistoryOptions)
    if (-not $global:__ghop_command) { return }
    $__ghop_stamp = Join-Path $global:__ghop_home 'daily.stamp'
    $__ghop_today = Get-Date -Format 'yyyy-MM-dd'
    if ((Test-Path -LiteralPath $__ghop_stamp) -and [IO.File]::ReadAllText($__ghop_stamp).Trim() -eq $__ghop_today) { return }
    $__ghop_directory = Join-Path $global:__ghop_home 'shell'
    [IO.Directory]::CreateDirectory($__ghop_directory) | Out-Null
    $__ghop_encoding = [Text.UTF8Encoding]::new($false)
    $__ghop_aliases = @(Get-Alias | ForEach-Object { @{ name = $_.Name; expansion = $_.Definition } })
    [IO.File]::WriteAllText((Join-Path $__ghop_directory 'powershell.aliases'), (ConvertTo-Json -InputObject $__ghop_aliases -Compress), $__ghop_encoding)
    $__ghop_functions = @(Get-ChildItem Function: | ForEach-Object { $_.Name })
    [IO.File]::WriteAllText((Join-Path $__ghop_directory 'powershell.functions'), ($__ghop_functions -join "\`n"), $__ghop_encoding)
    $__ghop_info = @('PS_VERSION=' + $PSVersionTable.PSVersion.ToString())
    if ($HistoryOptions) {
      $__ghop_info += 'HISTSIZE=' + $HistoryOptions.MaximumHistoryCount
      $__ghop_info += 'HISTORY_SAVE_STYLE=' + $HistoryOptions.HistorySaveStyle
      $__ghop_info += 'HISTORY_NO_DUPLICATES=' + [int]$HistoryOptions.HistoryNoDuplicates
      $__ghop_info += 'KEYMAP=' + $HistoryOptions.EditMode.ToString().ToLowerInvariant()
    }
    if ($env:STARSHIP_SHELL) { $__ghop_info += 'STARSHIP=1' }
    [IO.File]::WriteAllText((Join-Path $__ghop_directory 'powershell.info'), ($__ghop_info -join "\`n"), $__ghop_encoding)
    & $global:__ghop_command daily
  }

  function global:__ghop_precmd {
    if (-not $global:__ghop_started) {
      __ghop_install_capture
      $global:__ghop_started = $true
      $__ghop_options = $null
      if (Get-Command Get-PSReadLineOption -ErrorAction SilentlyContinue) {
        $__ghop_options = Get-PSReadLineOption
        $env:GHOP_HISTFILE = $__ghop_options.HistorySavePath
      }
      __ghop_daily $__ghop_options
    }
    $__ghop_fresh = Join-Path $global:__ghop_home 'fresh.flag'
    if ($global:__ghop_command -and (Test-Path -LiteralPath $__ghop_fresh)) {
      & $global:__ghop_command notify 2>$null
      if ($LASTEXITCODE -ne 0) { Remove-Item -LiteralPath $__ghop_fresh -Force -ErrorAction SilentlyContinue }
    }
  }

  $global:__ghop_original_prompt = (Get-Item Function:prompt).ScriptBlock
  function global:prompt {
    param($__ghop_success = $?, $__ghop_native_code = $global:LASTEXITCODE, $__ghop_error = $global:Error[0], $__ghop_completed_tick = [Diagnostics.Stopwatch]::GetTimestamp())
    $__ghop_prompt_text = & $global:__ghop_original_prompt
    $__ghop_code = Get-Variable LASTEXITCODE -ValueOnly -ErrorAction SilentlyContinue
    try { __ghop_record $__ghop_success $__ghop_native_code $__ghop_error $__ghop_completed_tick; __ghop_precmd } catch { } finally { $global:LASTEXITCODE = $__ghop_code }
    $__ghop_prompt_text
  }
  __ghop_install_capture
}
`;
