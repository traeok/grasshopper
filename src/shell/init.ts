  "  if [[ $(declare -p PROMPT_COMMAND 2>/dev/null) == 'declare -a '* ]]; then",
  "    PROMPT_COMMAND=(\"$__ghop_prompt_capture\" \"${PROMPT_COMMAND[@]}\" __ghop_precmd)",
  "  elif [[ ${PROMPT_COMMAND-} != *__ghop_precmd* ]]; then",
