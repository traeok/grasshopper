export function renderInit(shell: Shell, rootShellPath: string): string {
  const template = shell === "bash" ? BASH : shell === "zsh" ? ZSH : POWERSHELL_INIT;
  return template.replace("__ROOT__", () => rootShellPath.replaceAll("'", shell === "powershell" ? "''" : "'\\''"));
}

export function writeInitFile(shell: Shell): void {
  writeTextAtomic(initFile(shell), (shell === "powershell" ? "\uFEFF" : "") + renderInit(shell, toShellPath(ghopHome(), shell)));
}
